#!/usr/bin/env bash
# One-command LOCAL EVALUATION stack for EduOS (32.2.0).
#   ./scripts/dev-up.sh        (or: make up)
# Generates local secrets in .env.dev (git-ignored, mode 600) on first run,
# builds the images, starts PostgreSQL + migrate + API + Caddy HTTPS edge + the
# local development OIDC provider + webhook sink, seeds the synthetic demo
# district and prints the URL and demo logins. Never use this for production:
# see docs/UPGRADING-32.1.0.md and README.md for the production compose path.
set -euo pipefail
cd "$(dirname "$0")/.."

ENV_FILE=${EDUOS_DEV_ENV_FILE:-.env.dev}
HTTPS_PORT=${EDUOS_HTTPS_PORT:-8443}
HTTP_PORT=${EDUOS_HTTP_PORT:-8088}
IDP_PORT=${EDUOS_DEV_IDP_PORT:-9400}

command -v docker >/dev/null || { echo "docker is required (Docker Engine 24+ with the compose plugin)" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "the docker compose plugin (v2) is required" >&2; exit 1; }
docker info >/dev/null 2>&1 || { echo "cannot reach the Docker daemon (is it running, and may this user use it?)" >&2; exit 1; }

rand() { head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }

# The edge network needs a fixed subnet; pick one that no host route uses.
pick_subnet() {
  local routes; routes=$( (ip -4 route show 2>/dev/null || true) | awk '{print $1}')
  for prefix in 172.30.0 172.31.250 10.231.7 192.168.231; do
    if ! grep -q "^${prefix}\." <<<"$routes"; then echo "$prefix"; return; fi
  done
  echo "no free subnet for the edge network; set EDUOS_EDGE_SUBNET/EDUOS_EDGE_IP in $ENV_FILE" >&2; exit 1
}

if [ ! -f "$ENV_FILE" ]; then
  umask 077
  prefix=$(pick_subnet)
  cat > "$ENV_FILE" <<ENV
# Generated by scripts/dev-up.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). LOCAL EVALUATION ONLY.
# Delete this file (make down-volumes) to start over with new secrets.
NODE_ENV=development
PORT=8080
PUBLIC_ORIGIN=https://localhost:${HTTPS_PORT}
EDUOS_SITE_ADDRESS=localhost
EDUOS_HTTPS_PORT=${HTTPS_PORT}
EDUOS_HTTP_PORT=${HTTP_PORT}
EDUOS_DEV_IDP_PORT=${IDP_PORT}
EDUOS_EDGE_SUBNET=${prefix}.0/24
EDUOS_EDGE_IP=${prefix}.2
EDUOS_EDGE_IP_RANGE=${prefix}.128/25
POSTGRES_SUPERUSER=eduos_admin
POSTGRES_PASSWORD=$(rand 24)
EDUOS_OWNER_PASSWORD=$(rand 24)
EDUOS_APP_PASSWORD=$(rand 24)
EDUOS_APP_ROLE=eduos_app
DATABASE_SSL=false
# Local development OIDC provider (dev/dev-idp.js). Replace with your district IdP for anything real.
OIDC_ISSUER=http://devidp:9400
OIDC_CLIENT_ID=eduos-local
OIDC_CLIENT_SECRET=$(rand 24)
OIDC_REDIRECT_URI=https://localhost:${HTTPS_PORT}/auth/callback
OIDC_SCOPES=openid profile email
OIDC_EMAIL_VERIFICATION=claim
EDUOS_DEMO_MODE=false
WEBHOOK_SIGNING_KEY=$(rand 32)
WEBHOOK_ALLOW_INSECURE_LOOPBACK=true
METRICS_TOKEN=$(rand 16)
SESSION_IDLE_MINUTES=120
ENV
  echo "Generated local secrets in $ENV_FILE"
fi

# 32.2.0: LTI platform key for the demo LTI app (added to older .env.dev files too).
if ! grep -q '^LTI_PLATFORM_PRIVATE_KEY=.' "$ENV_FILE"; then
  if command -v openssl >/dev/null; then
    key=$(openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 2>/dev/null | awk '{printf "%s\\n",$0}')
    [ -n "$key" ] && { printf 'LTI_PLATFORM_PRIVATE_KEY=%s\n' "$key" >> "$ENV_FILE"; echo "Added a local LTI platform key to $ENV_FILE"; }
  else echo "openssl not found: LTI demo launches stay disabled" >&2; fi
fi

export EDUOS_ENV_FILE="$ENV_FILE"
DC=(docker compose --env-file "$ENV_FILE" -f docker-compose.yml -f docker-compose.dev.yml --profile edge)
get() { grep -E "^$1=" "$ENV_FILE" | tail -1 | cut -d= -f2-; }
HTTPS_PORT=$(get EDUOS_HTTPS_PORT); IDP_PORT=$(get EDUOS_DEV_IDP_PORT)

echo "Building images…"
"${DC[@]}" build --quiet

# 32.7.0: local EDEN trust root + district hub certificate (root key stays in
# .eden-dev/, git-ignored, mode 600). The app runs as the district hub.
mkdir -p .eden-dev && chmod 700 .eden-dev
docker run --rm --user "$(id -u):$(id -g)" -v "$PWD:/work" -w /work eduos-devtools:local \
  node src/eden/authority-cli.js dev-init --dir .eden-dev/authority --district-id 00000000-0000-4000-8000-000000000001 --env-file "$ENV_FILE"
echo "Starting PostgreSQL, migrations, API, HTTPS edge, dev OIDC provider and webhook sink…"
"${DC[@]}" up -d --remove-orphans

printf "Waiting for https://localhost:%s/health " "$HTTPS_PORT"
for _ in $(seq 1 90); do
  if curl -fsSk "https://localhost:${HTTPS_PORT}/health" >/dev/null 2>&1; then echo " ok"; break; fi
  printf "."; sleep 2
done
curl -fsSk "https://localhost:${HTTPS_PORT}/health" >/dev/null || {
  echo; echo "The stack did not become healthy. Recent logs:" >&2; "${DC[@]}" logs --tail 40 migrate app edge >&2; exit 1; }

echo "Seeding the synthetic demo district…"
"${DC[@]}" --profile seed run --rm seed

cat <<MSG

EduOS is running (LOCAL EVALUATION, synthetic data only).

  App:            https://localhost:${HTTPS_PORT}/
                  (Caddy's local CA; trust it with: make trust-ca, or accept the browser warning)
  Sign-in:        click "District sign-in"; the local OIDC provider on http://localhost:${IDP_PORT} lists the demo accounts
  Health:         https://localhost:${HTTPS_PORT}/health
  Stop:           make down        (keeps data)   ·   make down-volumes (deletes data and $ENV_FILE)
  Smoke test:     make smoke
  LTI demo tool:  node dev/lti-tool.js   (then launch "Science Lab (LTI demo)" from Apps)
  School nodes:   make eden-sim        (32.7.0: two simulated school nodes, partition + failover; see docs/EDEN-32.7.0.md)

Demo accounts:
MSG
"${DC[@]}" exec -T devidp node -e 'import("./dev/demo-fixture.js").then(m=>{for(const a of m.demoAccounts())console.log(`  ${a.name.padEnd(18)} ${a.role.padEnd(15)} ${a.school.padEnd(22)} ${a.note}`)})'
