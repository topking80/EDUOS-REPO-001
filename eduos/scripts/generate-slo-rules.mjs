#!/usr/bin/env node
// CMP-05: writes monitoring/eduos-slo.yml from src/slo.js.
//   node scripts/generate-slo-rules.mjs          write the file
//   node scripts/generate-slo-rules.mjs --check  fail if it is out of date
import fs from "node:fs";
import { SLOS, JOB, sliQueries, BURN_ALERTS, MIN_ALERT_RPS, PERIOD_DAYS } from "../src/slo.js";

const OUT = new URL("../monitoring/eduos-slo.yml", import.meta.url);
const SHORT = ["5m", "30m", "1h", "2h", "6h"];      // straight from counters
const LONG = { "1d": 288, "3d": 864, [`${PERIOD_DAYS}d`]: PERIOD_DAYS * 288 }; // from recorded 5m rates
const q = s => JSON.stringify(s); // YAML double-quoted scalars accept JSON strings

const cap = s => s[0].toUpperCase() + s.slice(1);
function burnAnnotations(slo, a) {
  const t = +(a.burn * (1 - slo.objective)).toFixed(6);
  return { summary: `EduOS ${slo.title.toLowerCase()} SLO: error budget burning ${a.burn}x`,
    description: `Over the last ${a.long} and ${a.short}, more than ${(t * 100).toFixed(3).replace(/\.?0+$/, "")}% of requests were bad (objective ${slo.objective * 100}%). At this rate the service spends ${a.spends}. Check recent deploys, eduos_http_requests_total by route, the database pool and dependencies.`,
    runbook: "docs/SLOS.md" };
}
function uptimeAnnotations() {
  const up = SLOS.find(s => s.id === "uptime");
  return { summary: `EduOS uptime is below its ${up.objective * 100}% objective for the last ${PERIOD_DAYS} days`,
    description: `The ${PERIOD_DAYS}-day uptime error budget is spent. Outages page through EduOSScrapeUnavailable; this alert is for planning: hold risky changes until the budget recovers (docs/SLOS.md).`,
    runbook: "docs/SLOS.md" };
}

export function render() {
  const out = [
    "# GENERATED by scripts/generate-slo-rules.mjs from src/slo.js. Do not edit by hand.",
    "# EduOS service level objectives (CMP-05): SLI recording rules, error budgets",
    "# and multi-window burn-rate alerts. Runbook: docs/SLOS.md",
    "# Needs Prometheus retention of at least " + PERIOD_DAYS + " days for the budget series.",
    "groups:"
  ];
  for (const slo of SLOS.filter(s => s.id !== "uptime")) {
    out.push(`  - name: eduos.slo.${slo.id}.recording`, "    interval: 1m", "    rules:");
    for (const w of SHORT) {
      const { total, bad } = sliQueries(slo.id, w);
      out.push(`      - record: eduos:slo_${slo.id}_requests:rate${w}`, `        expr: ${q(total)}`);
      out.push(`      - record: eduos:slo_${slo.id}_bad:rate${w}`, `        expr: ${q(bad)}`);
      out.push(`      - record: eduos:slo_${slo.id}_bad_ratio:rate${w}`,
        `        expr: ${q(`eduos:slo_${slo.id}_bad:rate${w} / clamp_min(eduos:slo_${slo.id}_requests:rate${w}, 1e-9)`)}`);
    }
    for (const w of Object.keys(LONG)) {
      out.push(`      - record: eduos:slo_${slo.id}_requests:rate${w}`, `        expr: ${q(`avg_over_time(eduos:slo_${slo.id}_requests:rate5m[${w}])`)}`);
      out.push(`      - record: eduos:slo_${slo.id}_bad_ratio:rate${w}`,
        `        expr: ${q(`sum_over_time(eduos:slo_${slo.id}_bad:rate5m[${w}]) / clamp_min(sum_over_time(eduos:slo_${slo.id}_requests:rate5m[${w}]), 1e-9)`)}`);
    }
    out.push(`      - record: eduos:slo_error_budget_remaining:ratio`,
      `        expr: ${q(`1 - eduos:slo_${slo.id}_bad_ratio:rate${PERIOD_DAYS}d / ${(1 - slo.objective).toFixed(6)}`)}`,
      `        labels:`, `          slo: ${slo.id}`);
    out.push(`      - record: eduos:slo_objective:ratio`, `        expr: vector(${slo.objective})`, `        labels:`, `          slo: ${slo.id}`);
  }
  // Uptime: at least one API instance scraped, minute by minute.
  out.push("  - name: eduos.slo.uptime.recording", "    interval: 1m", "    rules:",
    `      - record: eduos:slo_uptime_up:max`, `        expr: ${q(`max(up{job="${JOB}"}) or vector(0)`)}`);
  for (const w of ["1h", "1d", `${PERIOD_DAYS}d`])
    out.push(`      - record: eduos:slo_uptime_bad_ratio:rate${w}`, `        expr: ${q(`1 - avg_over_time(eduos:slo_uptime_up:max[${w}])`)}`);
  const up = SLOS.find(s => s.id === "uptime");
  out.push(`      - record: eduos:slo_error_budget_remaining:ratio`,
    `        expr: ${q(`1 - eduos:slo_uptime_bad_ratio:rate${PERIOD_DAYS}d / ${(1 - up.objective).toFixed(6)}`)}`, `        labels:`, `          slo: uptime`,
    `      - record: eduos:slo_objective:ratio`, `        expr: vector(${up.objective})`, `        labels:`, `          slo: uptime`);

  out.push("  - name: eduos.slo.alerts", "    rules:");
  for (const slo of SLOS.filter(s => s.id !== "uptime")) {
    const budget = 1 - slo.objective;
    const Id = cap(slo.id);
    for (const a of BURN_ALERTS) {
      const t = +(a.burn * budget).toFixed(6);
      out.push(`      - alert: EduOS${Id}BudgetBurn${a.name}`,
        `        expr: |`,
        `          eduos:slo_${slo.id}_bad_ratio:rate${a.long} > ${t}`,
        `          and eduos:slo_${slo.id}_bad_ratio:rate${a.short} > ${t}`,
        `          and eduos:slo_${slo.id}_requests:rate${a.long} > ${MIN_ALERT_RPS}`,
        `        for: ${a.for}`, `        labels:`, `          severity: ${a.severity}`, `          service: eduos`, `          slo: ${slo.id}`, `          window: ${a.long}`,
        `        annotations:`,
        ...Object.entries(burnAnnotations(slo, a)).map(([k, v]) => `          ${k}: ${q(v)}`));
    }
  }
  out.push(`      - alert: EduOSUptimeBudgetExhausted`,
    `        expr: eduos:slo_uptime_bad_ratio:rate${PERIOD_DAYS}d > ${(1 - up.objective).toFixed(6)}`,
    `        for: 10m`, `        labels:`, `          severity: warning`, `          service: eduos`, `          slo: uptime`, `          window: ${PERIOD_DAYS}d`,
    `        annotations:`, ...Object.entries(uptimeAnnotations()).map(([k, v]) => `          ${k}: ${q(v)}`));
  return out.join("\n") + "\n";
}

/**
 * promtool unit tests (monitoring/eduos-slo.test.yml). The scenarios and which
 * alerts must fire are chosen here; only the alert text comes from render().
 */
export function renderTests() {
  const L = 'job="eduos",method="GET",route="/api/home",instance="a"';
  const series = (name, labels, values) => [`      - series: ${q(`${name}{${labels}}`)}`, `        values: ${q(values)}`];
  const traffic = ({ ok, err = 0, fast, slow = 0, mins = 120, up = `1x${mins}` }) => [
    ...series("eduos_http_requests_total", `${L},status="2xx"`, `0+${ok}x${mins}`),
    ...series("eduos_http_requests_total", `${L},status="5xx"`, `0+${err}x${mins}`),
    ...series("eduos_http_request_duration_seconds_count", `${L},status="2xx"`, `0+${fast + slow}x${mins}`),
    ...series("eduos_http_request_duration_seconds_bucket", `${L},status="2xx",le="1"`, `0+${fast}x${mins}`),
    ...series("up", 'job="eduos",instance="a"', up)];
  const burn = (id, name) => { const slo = SLOS.find(s => s.id === id), a = BURN_ALERTS.find(b => b.name === name);
    return { alert: `EduOS${cap(id)}BudgetBurn${name}`, labels: { severity: a.severity, service: "eduos", slo: id, window: a.long }, annotations: burnAnnotations(slo, a) }; };
  const ALL = SLOS.filter(s => s.id !== "uptime").flatMap(s => BURN_ALERTS.map(a => `EduOS${cap(s.id)}BudgetBurn${a.name}`)).concat("EduOSUptimeBudgetExhausted");
  const alertsAt = (at, firing) => ALL.flatMap(name => {
    const f = firing.find(x => x.alert === name);
    const head = [`      - eval_time: ${at}`, `        alertname: ${name}`];
    if (!f) return [...head, "        exp_alerts: []"];
    return [...head, "        exp_alerts:", "          - exp_labels:", ...Object.entries(f.labels).map(([k, v]) => `              ${k}: ${q(v)}`),
      "            exp_annotations:", ...Object.entries(f.annotations).map(([k, v]) => `              ${k}: ${q(v)}`)];
  });
  const expr = (at, e, value) => [`      - expr: ${q(e)}`, `        eval_time: ${at}`, "        exp_samples:", `          - labels: ${q(value.labels || "{}")}`, `            value: ${value.value}`];
  const t = (name, input, alerts, exprs = []) => ["  # " + name, "  - interval: 1m", "    input_series:", ...input,
    "    alert_rule_test:", ...alerts, ...(exprs.length ? ["    promql_expr_test:", ...exprs] : [])];
  const out = ["# GENERATED by scripts/generate-slo-rules.mjs. Run: promtool test rules monitoring/eduos-slo.test.yml",
    "rule_files:", "  - eduos-slo.yml", "evaluation_interval: 1m", "tests:",
    // 10 requests/s, all good. Server errors on /metrics don't count.
    ...t("Healthy: no alerts, full budget; monitoring routes are excluded", [...traffic({ ok: 600, fast: 600 }),
      ...series("eduos_http_requests_total", 'job="eduos",method="GET",route="/metrics",instance="a",status="5xx"', "0+600x120")],
      alertsAt("100m", []),
      [...expr("100m", 'eduos:slo_error_budget_remaining:ratio{slo="availability"}', { labels: 'eduos:slo_error_budget_remaining:ratio{slo="availability"}', value: 1 }),
       ...expr("100m", 'eduos:slo_error_budget_remaining:ratio{slo="uptime"}', { labels: 'eduos:slo_error_budget_remaining:ratio{slo="uptime"}', value: 1 })]),
    // 10% of requests fail: the fast and steady burns page; slower ones are still pending.
    ...t("Outage: 10% server errors", traffic({ ok: 540, err: 60, fast: 600 }),
      alertsAt("30m", [burn("availability", "Fast"), burn("availability", "Steady")]),
      expr("30m", 'eduos:slo_error_budget_remaining:ratio{slo="availability"} < bool 0', { labels: '{slo="availability"}', value: 1 })),
    // Half of requests take over a second.
    ...t("Slow responses: half over 1s", traffic({ ok: 600, fast: 300, slow: 300 }),
      alertsAt("30m", [burn("latency", "Fast"), burn("latency", "Steady")])),
    // 0.005 requests/s, half failing: too little traffic to page anyone.
    ...t("Quiet hours: a few failures among very few requests", traffic({ ok: 0.15, err: 0.15, fast: 0.3 }),
      alertsAt("30m", [])),
    // The API can't be scraped for 15 minutes of two hours.
    ...t("Down for 15 minutes", traffic({ ok: 600, fast: 600, up: "1x60 0x15 1x45" }),
      alertsAt("110m", [{ alert: "EduOSUptimeBudgetExhausted", labels: { severity: "warning", service: "eduos", slo: "uptime", window: `${PERIOD_DAYS}d` }, annotations: uptimeAnnotations() }]))
  ];
  return out.join("\n") + "\n";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = [[OUT, render()], [new URL("../monitoring/eduos-slo.test.yml", import.meta.url), renderTests()]];
  for (const [file, text] of files) {
    if (process.argv.includes("--check")) {
      if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) { console.error(`${file.pathname} is out of date: run node scripts/generate-slo-rules.mjs`); process.exit(1); }
    } else fs.writeFileSync(file, text);
  }
}
